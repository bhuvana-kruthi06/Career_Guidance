CREATE TABLE users (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, email VARCHAR(254) NOT NULL UNIQUE, password_hash VARCHAR(60) NOT NULL,
 role VARCHAR(16) NOT NULL DEFAULT 'USER', is_active BOOLEAN NOT NULL DEFAULT TRUE, full_name VARCHAR(80) NULL,
 account_status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE', last_active_at TIMESTAMP NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT chk_test_user_role CHECK(role IN ('USER','ADMIN')),
 CONSTRAINT chk_test_user_status CHECK(account_status IN ('ACTIVE','SUSPENDED','ARCHIVED'))
);
CREATE TABLE refresh_tokens (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,user_id BIGINT NOT NULL,token_hash CHAR(64) NOT NULL UNIQUE,expires_at TIMESTAMP NOT NULL,
 revoked_at TIMESTAMP NULL,replaced_by_hash CHAR(64) NULL,created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE TABLE student_profiles (
 user_id BIGINT PRIMARY KEY,profile_json TEXT NOT NULL,local_imported BOOLEAN NOT NULL DEFAULT FALSE,
 target_role_code VARCHAR(15) NULL,target_role_title VARCHAR(160) NULL,profile_completeness TINYINT NOT NULL DEFAULT 0,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE TABLE match_sessions (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,user_id BIGINT NOT NULL,skills_snapshot TEXT NOT NULL,interests_snapshot TEXT NOT NULL,
 results_json TEXT NOT NULL,created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE TABLE match_results (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,session_id BIGINT NOT NULL,result_rank INT NOT NULL,onet_soc_code VARCHAR(15) NOT NULL,
 result_json TEXT NOT NULL,UNIQUE(session_id,result_rank),FOREIGN KEY(session_id) REFERENCES match_sessions(id) ON DELETE CASCADE
);
CREATE TABLE saved_careers (
 user_id BIGINT NOT NULL,onet_soc_code VARCHAR(15) NOT NULL,career_json TEXT NOT NULL,created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(user_id,onet_soc_code),FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE TABLE roadmap_items (
 user_id BIGINT NOT NULL,item_key VARCHAR(120) NOT NULL,item_json TEXT NOT NULL,is_complete BOOLEAN NOT NULL DEFAULT FALSE,
 completed_at TIMESTAMP NULL,updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,PRIMARY KEY(user_id,item_key),
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE TABLE career_assessments (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,user_id BIGINT NOT NULL,assessment_json TEXT NOT NULL,recommendations_json TEXT NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE TABLE resume_analyses (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,user_id BIGINT NOT NULL,target_role_code VARCHAR(15) NULL,extracted_json TEXT NOT NULL,
 report_json TEXT NOT NULL,created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE TABLE skill_gap_progress (
 user_id BIGINT NOT NULL,role_code VARCHAR(15) NOT NULL,skill_name VARCHAR(160) NOT NULL,status VARCHAR(20) NOT NULL,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,PRIMARY KEY(user_id,role_code,skill_name),
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE TABLE career_tool_records (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,user_id BIGINT NOT NULL,record_type VARCHAR(32) NOT NULL,record_key VARCHAR(80) NOT NULL,
 status VARCHAR(24) NULL,record_json TEXT NOT NULL,created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,UNIQUE(user_id,record_type,record_key),FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE TABLE job_applications (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,user_id BIGINT NOT NULL,company VARCHAR(160) NOT NULL,role_title VARCHAR(180) NOT NULL,
 job_link VARCHAR(1200) NULL,salary VARCHAR(120) NULL,location VARCHAR(160) NULL,resume_version VARCHAR(160) NULL,
 application_date DATE NULL,status VARCHAR(32) NOT NULL DEFAULT 'Saved',notes VARCHAR(4000) NULL,follow_up_date DATE NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE TABLE admin_user_notes (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,user_id BIGINT NOT NULL,admin_id BIGINT NOT NULL,note VARCHAR(2000) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY(admin_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE TABLE admin_audit_logs (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,admin_id BIGINT NOT NULL,action VARCHAR(48) NOT NULL,subject_type VARCHAR(32) NOT NULL,
 subject_id VARCHAR(80) NOT NULL,details_json TEXT NOT NULL,created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(admin_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE TABLE admin_content_items (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,content_type VARCHAR(32) NOT NULL,title VARCHAR(200) NOT NULL,content_json TEXT NOT NULL,
 enabled BOOLEAN NOT NULL DEFAULT TRUE,archived_at TIMESTAMP NULL,created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
